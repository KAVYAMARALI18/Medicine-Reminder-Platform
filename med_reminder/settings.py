def load_environment_file(path):
    if not path.is_file():
        return

    for line_number, line in enumerate(path.read_text(encoding='utf-8-sig').splitlines(), start=1):
        entry = line.strip()
        if not entry or entry.startswith('#'):
            continue
        if entry.startswith('export '):
            entry = entry[7:].lstrip()

        shell_entry = re.fullmatch(
            r'(?:\$env:|set\s+)?([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.*)',
            entry,
            flags=re.IGNORECASE,
        )
        if shell_entry:
            key, raw_value = shell_entry.groups()
        else:
            key, separator, raw_value = entry.partition('=')
            if not separator or not key.isidentifier():
                logging.getLogger(__name__).warning(
                    'Ignoring invalid environment setting in %s at line %d.',
                    path.name,
                    line_number,
                )
                continue

        if not key.isidentifier():
            raise ValueError(f'Invalid environment setting in {path.name} at line {line_number}.')

        try:
            value = ' '.join(shlex.split(raw_value.strip(), comments=True))
        except ValueError as exc:
            raise ValueError(f'Invalid quoting in {path.name} at line {line_number}.') from exc
        os.environ.setdefault(key, value)


load_environment_file(BASE_DIR / '.env')


